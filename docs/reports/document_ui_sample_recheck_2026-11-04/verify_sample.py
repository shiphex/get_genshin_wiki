"""Limited independent expectations: twelve known rows and two new controls.

The expected source text, types and speakers are not generated by the production
parser. Collection/replay is a separate consistency check, not a semantic oracle.
"""
from collections import Counter
import contextlib
import hashlib
import importlib.util
import io
import json
from pathlib import Path
import re
import sys

import mwparserfromhell as mw

ROOT = next(p for p in Path(__file__).resolve().parents if (p / 'pyproject.toml').is_file())
OUT = ROOT / '.uv-cache/independent-sample-audit-2026-11-04'
SAMPLES = {'archon-quests': ['三个心愿'],
           'character-quests': ['真实亦是谎言', '一切代价的回旋'],
           'event-quests': ['《勇敢的北风》']}


def module(name, file):
    spec = importlib.util.spec_from_file_location(name, ROOT / file)
    result = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(result)
    return result


def load(family, suffix):
    path = next((ROOT / 'data/pages').glob('*__' + suffix + '.json'))
    payload = json.loads(path.read_bytes())
    page = next(iter(payload['query']['pages'].values()))
    text = page['revisions'][0]['slots']['main']['*']
    saved = json.loads((ROOT / 'data/parsed' / family / path.name).read_bytes())
    return path, payload, page['title'], text, saved


def known_rows():
    notes = ['———雅珂达', '———杜林', '———派蒙', '——坎托尔', '旁边有他们的对话']
    evidence = []
    for family, suffix, line_numbers in [
        ('character-quests', '6a586c4ae4', [67, 69, 71, 300, 307, 316]),
        ('archon-quests', '9cc68e31c8', [824, 826, 828, 830, 832, 834]),
    ]:
        path, payload, title, text, saved = load(family, suffix)
        for number in line_numbers:
            source = text.splitlines()[number - 1]
            expected = source.strip().removeprefix('*')
            for note in notes:
                expected = expected.replace('{{黑幕|' + note + '}}', '')
            expected = expected.replace('<br>', '').strip()
            matches = [(i, r) for i, r in enumerate(saved['对话']) if r['内容'] == expected]
            passed = len(matches) == 1 and matches[0][1]['类型'] == 'narration' and matches[0][1]['说话者'] == ''
            evidence.append({'title': title, 'raw_line': number, 'raw': source,
                             'expected_content': expected, 'actual_matches': matches, 'pass': passed})
    persisted = [json.loads(line) for line in (ROOT / 'data/reports/fold-dialogue-0605-annotations.jsonl').read_text(encoding='utf-8').splitlines()]
    annotations = [{'text': note, 'matching_count': sum(n['source']['page_title'] == '月亮回家的夜晚' and n['text'] == note for n in persisted)} for note in notes]
    return {'rows': evidence, 'known_row_count': len(evidence),
            'passed_row_count': sum(e['pass'] for e in evidence), 'annotations': annotations,
            'pass': all(e['pass'] for e in evidence) and all(a['matching_count'] == 1 for a in annotations)}


def controls():
    # This independently written renderer supports exactly the inline syntax
    # manually read in these two controls. It does not import production code.
    display = module('november_source_display', 'docs/reports/fold_dialogue_sample_recheck_2026-10-31/check_main_samples.py').visible
    results = []
    for family, suffix in [('archon-quests', 'fbcab0e3d8'), ('event-quests', '763649e7cd')]:
        path, payload, title, text, saved = load(family, suffix)
        source = re.sub(r'<!--[\s\S]*?-->', lambda m: '\n' * m.group().count('\n'), text)
        start = source.index('==任务剧情==')
        expected = []
        for line in source[start:].splitlines():
            line = re.sub(r'^\|(?:剧情\d+|内容)=', '', line).strip().removeprefix('*')
            match = re.match(r'([^：\n{}|]+)：(.*)', line)
            if match:
                who, content = match.groups()
                expected.append((display(who).strip(), display(content).rstrip('}').strip()))
        expected_groups = []
        for template in mw.parse(source[start:]).filter_templates(recursive=True):
            if str(template.name).strip() == '剧情选项':
                expected_groups.append([str(template.get('选项' + str(i)).value).strip() for i in range(1, 30) if template.has('选项' + str(i))])
        if family == 'event-quests':
            rows = [r for step in saved['剧情对话'] for r in step['对话']]
            actual = [(r['说话者'], r['内容']) for r in rows if r.get('说话者')]
            actual_groups = [r['选项'] for r in rows if r['类型'] == '选项']
            option_equal = actual_groups == expected_groups
            actual_options = [label for group in actual_groups for label in group]
        else:
            rows = saved['对话']
            actual = [(r['说话者'], r['内容']) for r in rows if r['类型'] in {'character', 'traveler'}]
            actual_options = [r['内容'] for r in rows if r['类型'] == 'option']
            option_equal = actual_options == [label for group in expected_groups for label in group]
        results.append({'title': title, 'raw_speaker_rows': len(expected), 'actual_speaker_rows': len(actual),
                        'speaker_and_content_sequence_equal': expected == actual,
                        'option_labels': len(actual_options), 'option_order_equal': option_equal,
                        'missing': list((Counter(expected) - Counter(actual)).items()),
                        'extra': list((Counter(actual) - Counter(expected)).items())})
    return results


def run():
    OUT.mkdir(parents=True, exist_ok=True)
    collector = module('november_sample_collector', 'docs/reports/fold_dialogue_sample_audit_2026-10-30/audit_sample.py')
    collector.SAMPLES, collector.OUT = SAMPLES, OUT
    inputs = {}
    for family, titles in SAMPLES.items():
        for title in titles:
            path = next((ROOT / 'data/pages').glob(title + '__*.json'))
            for item in (path, ROOT / 'data/parsed' / family / path.name):
                inputs[item.relative_to(ROOT).as_posix()] = hashlib.sha256(item.read_bytes()).hexdigest()
    with contextlib.redirect_stdout(io.StringIO()):
        collector.run()
    collection = json.loads((OUT / 'summary.json').read_bytes())
    result = {'known_rows': known_rows(), 'controls': controls(), 'collection': collection,
              'code_sha256': {name: hashlib.sha256((ROOT / name).read_bytes()).hexdigest() for name in (
                  'get_genshin_wiki/recovery/extract.py', 'get_genshin_wiki/recovery/display.py',
                  'get_genshin_wiki/recovery/legacy.py')},
              'input_and_business_files_unchanged': all(hashlib.sha256((ROOT / name).read_bytes()).hexdigest() == digest for name, digest in inputs.items())}
    result['verdict'] = 'PASS_KNOWN_ROWS_AND_TWO_CONTROLS_ONLY' if result['known_rows']['pass'] and all(r['speaker_and_content_sequence_equal'] and r['option_order_equal'] for r in result['controls']) else 'REJECT'
    (OUT / 'known_and_controls.json').write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding='utf-8')
    print(json.dumps({'verdict': result['verdict'], 'known_rows_passed': result['known_rows']['passed_row_count'],
                      'new_collected_samples': len(collection), 'controls': result['controls'],
                      'input_and_business_files_unchanged': result['input_and_business_files_unchanged']}, ensure_ascii=False))
    return result


if __name__ == '__main__':
    sys.exit(0 if run()['verdict'] == 'PASS_KNOWN_ROWS_AND_TWO_CONTROLS_ONLY' else 1)
